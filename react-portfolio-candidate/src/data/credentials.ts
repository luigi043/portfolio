export function getVerificationUrl(certificate: Certification) {
  const path =
    certificate.kind === "Professional Certificate"
      ? "professional-cert"
      : certificate.kind === "Specialization"
        ? "specialization"
        : "";

  return `https://www.coursera.org/verify/${path ? `${path}/` : ""}${certificate.id}`;
}

